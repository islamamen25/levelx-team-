const p = $input.first().json; // أو حسب اسم المتغير عندك

// Slug — من serial أو ASIN (مش الاسم العربي عشان هيتمسح كله)
const base = (p.serial || p.asin || '')
  .replace(/[^a-zA-Z0-9]/g, '-')
  .toLowerCase()
  .replace(/^-+|-+$/g, '');
const slug = base || ('p-' + (p.serial || p.asin || 'unknown'));

// Brand
const brand =
  (p.allSpecs && (p.allSpecs['Brand'] || p.allSpecs['brand'] || p.allSpecs['العلامة التجارية'])) ||
  p.brand ||
  null;

// ai_metadata (بيحل محل asin + amazon_url كحقول مستقلة)
const ai_metadata = {
  asin: p.asin || null,
  amazon_url: p.url || p.productUrl || null,
  asin_status: (!p.asin || p.asin.startsWith('NOASIN')) ? 'missing' : 'found'
};

return [{ json: { ...p, slug, brand, ai_metadata } }];


